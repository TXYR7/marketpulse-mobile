import {readFileSync,writeFileSync,existsSync} from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
const root=fileURLToPath(new URL('../',import.meta.url));
const desktop=process.env.MP_DESKTOP_ROOT || path.resolve(root,'../codex');
if(!existsSync(path.join(desktop,'backtest-execution.js')))throw Error('MP_DESKTOP_ROOT需指向当前桌面仓库');
const read=file=>readFileSync(path.join(desktop,file),'utf8').replaceAll('\r\n','\n');
const esm=source=>source.replace(/module\.exports\s*=\s*\{([\s\S]*?)\};\s*$/,'export {$1};\n');
for(const file of ['advisor-core.js','backtest-execution.js','strategies.js'])writeFileSync(path.join(root,file),esm(read(file)));
const source=read('analytics.js');
function extract(name){
 const start=source.indexOf('function '+name+'(');if(start<0)throw Error('Missing '+name);
 let depth=0,body=-1,paren=0;
 for(let i=source.indexOf('(',start);i<source.length;i++){
  if(body<0){if(source[i]==='(')paren++;else if(source[i]===')')paren--;else if(source[i]==='{'&&paren===0)body=i;}
  if(body>=0){if(source[i]==='{')depth++;else if(source[i]==='}'&&--depth===0)return source.slice(start,i+1);}
 }
 throw Error('Unclosed '+name);
}
const names=['finiteNumber','round','hasNumericField','summarizeTheme','groupThemes','buyTypeOf','dayContext','approximatePhaseOf','quoteClose','priceLimitRatio','isOnePriceLimit','executableReturn','monteCarloBootstrap','calendarDayGap','runBacktest','aggregateBacktests'];
const constants=source.slice(source.indexOf('const DEFAULT_BACKTEST_COSTS'),source.indexOf('function quoteClose')).trim();
const phase=source.match(/^const PHASE_NAMES = [^\n]+/m)[0];
const body=constants+'\n'+phase+'\n'+names.map(extract).join('\n\n');
const version=createHash('sha256').update(body+read('backtest-execution.js')+read('strategies.js')).digest('hex').slice(0,16);
writeFileSync(path.join(root,'backtest-core.js'),`// Generated by scripts/sync-research.mjs from desktop pure functions.\nimport {strategyMatches} from './strategies.js';\nimport {tradePath,simulatePortfolio} from './backtest-execution.js';\nexport const BACKTEST_SOURCE_VERSION='${version}';\n${body}\nexport {runBacktest,aggregateBacktests,dayContext};\n`);
console.log('Synced research calculation '+version);
const signalSource=['analytics.js','unified-context.js','unified-judgement.js','mobile-model.js','signal-core.js'].map(file=>readFileSync(path.join(root,file),'utf8').replaceAll('\r\n','\n')).join('\n');
const signalVersion=createHash('sha256').update(signalSource).digest('hex').slice(0,16);
writeFileSync(path.join(root,'research-version.js'),`// Generated source identity; separates signal cohorts after rule changes.\nexport const SIGNAL_SOURCE_VERSION='${signalVersion}';\n`);
